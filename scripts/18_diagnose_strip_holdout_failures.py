def subset_definitions(
    ph_levels: Sequence[float],
    highlighted_ph: Sequence[float],
) -> list[tuple[str, set[float]]]:
    ph_set = set(float(value) for value in ph_levels)
    minimum = float(min(ph_levels))
    maximum = float(max(ph_levels))
    highlighted = set(
        float(value)
        for value in highlighted_ph
        if float(value) in ph_set
    )

    definitions = [
        ("all_ph", ph_set),
        ("boundary_ph_1_13", {minimum, maximum}),
        (
            "interior_ph_2_12",
            {
                value
                for value in ph_set
                if minimum < value < maximum
            },
        ),
        (
            "strict_interior_ph_3_11",
            {
                value
                for value in ph_set
                if minimum + 1 < value < maximum - 1
            },
        ),
    ]

    if highlighted:
        definitions.append(
            ("highlighted_ph", highlighted)
        )
        definitions.append(
            ("non_highlighted_ph", ph_set - highlighted)
        )

    return definitions


def build_subset_sensitivity(
    paired: pd.DataFrame,
    highlighted_ph: Sequence[float],
    trim_fraction: float,
    repetitions: int,
    seed: int,
) -> pd.DataFrame:
    ph_levels = sorted(
        paired["ph_nominal"].unique().tolist()
    )
    definitions = subset_definitions(
        ph_levels,
        highlighted_ph,
    )
    rows: list[dict[str, Any]] = []

    for (
        basis_count,
        region,
    ), group in paired.groupby(
        ["basis_count", "region"],
        sort=True,
    ):
        for subset_name, subset_values in definitions:
            subset = group.loc[
                group["ph_nominal"].isin(
                    subset_values
                )
            ].copy()

            row = {
                "basis_count": int(basis_count),
                "region": region,
                "subset": subset_name,
                "included_ph": ",".join(
                    f"{value:g}"
                    for value in sorted(subset_values)
                ),
            }
            row.update(
                robust_summary_row(
                    subset,
                    "mean_deltaE76_difference",
                    trim_fraction,
                    repetitions,
                    seed,
                    stratify_by_phone=True,
                )
            )
            rows.append(row)

    return pd.DataFrame(rows)


