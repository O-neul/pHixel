#!/usr/bin/env python
"""
11_train_local_context_binary_layer4.py

Train local-context image classifiers with two-stage transfer learning for one binary LOPO split.

Methods
-------
- baseline:
    Fixed local-context image, no color augmentation.
- color_jitter:
    Fixed local-context image with mild torchvision ColorJitter.
- nuisance_structured:
    Empirical train-only nuisance transfer on the native local crop:
      background delta -> whole local crop
      contrast delta   -> feathered LabelMe ROI inside the crop
    The transformed crop is then letterboxed with fixed white padding.

Task
----
- acidic: pH 1-6
- alkaline: pH 8-13
- pH 7 excluded

Leakage controls
----------------
- The local-context manifest must contain all 195 original samples.
- Train/validation/test membership comes from the supplied split CSV.
- Nuisance components must come from the matching train-only binary
  decomposition directory.
- ImageNet normalization is used for pretrained ResNet18.
- Model selection uses validation metrics only.
- Test is evaluated after the best validation checkpoint is selected.
"""

