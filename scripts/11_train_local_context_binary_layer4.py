def resolve_existing(path: Path) -> Path:
    candidates = [path]
    if not path.is_absolute():
        candidates.extend([PROJECT_ROOT / path, Path.cwd() / path])
    for candidate in candidates:
        candidate = candidate.resolve()
        if candidate.exists():
            return candidate
    raise FileNotFoundError(f"Path not found: {path}")


def resolve_output(path: Path) -> Path:
    if path.is_absolute():
        return path.resolve()
    return (PROJECT_ROOT / path).resolve()


def find_column(
    frame: pd.DataFrame,
    candidates: Iterable[str],
    description: str,
) -> str:
    lower = {str(column).lower(): str(column) for column in frame.columns}
    for candidate in candidates:
        if candidate in frame.columns:
            return candidate
        if candidate.lower() in lower:
            return lower[candidate.lower()]
    raise ValueError(
        f"Could not identify {description}. Tried {list(candidates)}. "
        f"Available columns: {list(frame.columns)}"
    )


def parse_methods(raw: str) -> list[str]:
    values = [item.strip() for item in raw.split(",") if item.strip()]
    if not values:
        raise ValueError("At least one method is required.")
    unknown = sorted(set(values) - METHODS)
    if unknown:
        raise ValueError(
            f"Unknown methods: {unknown}. Allowed: {sorted(METHODS)}"
        )
    return list(dict.fromkeys(values))


def validate_args(args: argparse.Namespace) -> None:
    integer_positive = {
        "warmup_epochs": args.warmup_epochs,
        "finetune_epochs": args.finetune_epochs,
        "batch_size": args.batch_size,
        "image_size": args.image_size,
        "min_finetune_epochs": args.min_finetune_epochs,
    }
    for name, value in integer_positive.items():
        if value <= 0:
            raise ValueError(f"--{name.replace('_', '-')} must be > 0.")

    if args.patience < 1:
        raise ValueError("--patience must be at least 1.")
    if args.min_finetune_epochs > args.finetune_epochs:
        raise ValueError(
            "--min-finetune-epochs cannot exceed --finetune-epochs."
        )
    if args.num_workers < 0:
        raise ValueError("--num-workers must be >= 0.")

    positive = {
        "head_learning_rate": args.head_learning_rate,
        "layer4_learning_rate": args.layer4_learning_rate,
        "overall_scale": args.overall_scale,
    }
    for name, value in positive.items():
        if not math.isfinite(value) or value <= 0:
            raise ValueError(f"--{name.replace('_', '-')} must be > 0.")

    nonnegative = {
        "weight_decay": args.weight_decay,
        "phone_scale": args.phone_scale,
        "light_scale": args.light_scale,
        "interaction_scale": args.interaction_scale,
        "residual_scale": args.residual_scale,
        "feather_radius": args.feather_radius,
        "jitter_brightness": args.jitter_brightness,
        "jitter_contrast": args.jitter_contrast,
        "jitter_saturation": args.jitter_saturation,
        "jitter_hue": args.jitter_hue,
    }
    for name, value in nonnegative.items():
        if not math.isfinite(value) or value < 0:
            raise ValueError(f"--{name.replace('_', '-')} must be >= 0.")

    if not 0.0 <= args.nuisance_probability <= 1.0:
        raise ValueError("--nuisance-probability must be in [0, 1].")


def set_global_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)

    try:
        torch.use_deterministic_algorithms(True, warn_only=True)
    except Exception:
        pass

    if hasattr(torch.backends, "cudnn"):
        torch.backends.cudnn.benchmark = False
        torch.backends.cudnn.deterministic = True


def choose_device(requested: str) -> torch.device:
    if requested == "cpu":
        return torch.device("cpu")
    if requested == "cuda":
        if not torch.cuda.is_available():
            raise RuntimeError("CUDA was requested but is not available.")
        return torch.device("cuda")
    return torch.device("cuda" if torch.cuda.is_available() else "cpu")


