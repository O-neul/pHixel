def first_matching(
    frame: pd.DataFrame,
    **conditions: str,
) -> pd.Series:
    mask = np.ones(len(frame), dtype=bool)
    for column, value in conditions.items():
        mask &= (
            frame[column].astype(str).to_numpy() == str(value)
        )
    matched = frame.loc[mask]
    if matched.empty:
        raise KeyError(f"No nuisance row matched {conditions}")
    return matched.iloc[0]


def srgb_to_lab(rgb_01: np.ndarray) -> np.ndarray:
    rgb = np.asarray(rgb_01, dtype=np.float64)
    linear = np.where(
        rgb <= 0.04045,
        rgb / 12.92,
        ((rgb + 0.055) / 1.055) ** 2.4,
    )
    matrix = np.array([
        [0.4124564, 0.3575761, 0.1804375],
        [0.2126729, 0.7151522, 0.0721750],
        [0.0193339, 0.1191920, 0.9503041],
    ])
    xyz = linear @ matrix.T
    white = np.array([0.95047, 1.0, 1.08883])
    scaled = xyz / white
    delta = 6.0 / 29.0
    f = np.where(
        scaled > delta**3,
        np.cbrt(scaled),
        scaled / (3.0 * delta**2) + 4.0 / 29.0,
    )
    return np.stack(
        [
            116.0 * f[..., 1] - 16.0,
            500.0 * (f[..., 0] - f[..., 1]),
            200.0 * (f[..., 1] - f[..., 2]),
        ],
        axis=-1,
    )


def lab_to_srgb_unclipped(lab: np.ndarray) -> np.ndarray:
    lab = np.asarray(lab, dtype=np.float64)
    fy = (lab[..., 0] + 16.0) / 116.0
    fx = fy + lab[..., 1] / 500.0
    fz = fy - lab[..., 2] / 200.0
    delta = 6.0 / 29.0

    def inverse_f(value: np.ndarray) -> np.ndarray:
        return np.where(
            value > delta,
            value**3,
            3.0 * delta**2 * (value - 4.0 / 29.0),
        )

    white = np.array([0.95047, 1.0, 1.08883])
    xyz = (
        np.stack(
            [inverse_f(fx), inverse_f(fy), inverse_f(fz)],
            axis=-1,
        )
        * white
    )
    inverse_matrix = np.array([
        [3.2404542, -1.5371385, -0.4985314],
        [-0.9692660, 1.8760108, 0.0415560],
        [0.0556434, -0.2040259, 1.0572252],
    ])
    linear = xyz @ inverse_matrix.T
    positive = np.maximum(linear, 0.0)
    return np.where(
        linear <= 0.0031308,
        12.92 * linear,
        1.055 * positive ** (1.0 / 2.4) - 0.055,
    )


def make_feather_mask(
    image_size: tuple[int, int],
    bbox: tuple[float, float, float, float],
    feather_radius: float,
) -> np.ndarray:
    mask = Image.new("L", image_size, 0)
    draw = ImageDraw.Draw(mask)
    draw.rectangle(bbox, fill=255)
    if feather_radius > 0:
        mask = mask.filter(
            ImageFilter.GaussianBlur(radius=float(feather_radius))
        )
    return np.asarray(mask, dtype=np.float64) / 255.0


def letterbox_white(
    image: Image.Image,
    output_size: int,
) -> Image.Image:
    source = image.convert("RGB")
    scale = min(
        output_size / source.width,
        output_size / source.height,
    )
    width = max(1, int(round(source.width * scale)))
    height = max(1, int(round(source.height * scale)))
    resized = source.resize(
        (width, height),
        Image.Resampling.LANCZOS,
    )
    canvas = Image.new(
        "RGB",
        (output_size, output_size),
        (255, 255, 255),
    )
    offset_x = (output_size - width) // 2
    offset_y = (output_size - height) // 2
    canvas.paste(resized, (offset_x, offset_y))
    return canvas


class StructuredNuisanceTransfer:
    def __init__(
        self,
        library: pd.DataFrame,
        phone_scale: float,
        light_scale: float,
        interaction_scale: float,
        residual_scale: float,
        overall_scale: float,
        feather_radius: float,
        image_size: int,
    ) -> None:
        self.library = library.copy()
        self.phone_scale = float(phone_scale)
        self.light_scale = float(light_scale)
        self.interaction_scale = float(interaction_scale)
        self.residual_scale = float(residual_scale)
        self.overall_scale = float(overall_scale)
        self.feather_radius = float(feather_radius)
        self.image_size = int(image_size)

        bg = self.library.loc[
            self.library["region"].astype(str) == "bg"
        ].copy()
        self.phones = sorted(
            bg["phone_id"].astype(str).unique().tolist()
        )
        self.lights = sorted(
            bg["light_id"].astype(str).unique().tolist()
        )
        self.cells = sorted(
            set(
                zip(
                    bg["phone_id"].astype(str),
                    bg["light_id"].astype(str),
                )
            )
        )
        self.image_ids = sorted(
            bg["image_id"].astype(str).unique().tolist()
        )

        if not self.phones or not self.lights or not self.cells:
            raise ValueError("Nuisance library has no train conditions.")

    def sample_target(
        self,
        source_phone: str,
        source_light: str,
        rng: random.Random,
    ) -> dict[str, str]:
        eligible = [
            cell
            for cell in self.cells
            if cell != (source_phone, source_light)
        ]
        if not eligible:
            raise ValueError(
                "No nuisance target condition differs from the source."
            )
        target_phone, target_light = rng.choice(eligible)
        residual_image = rng.choice(self.image_ids)
        return {
            "target_phone": target_phone,
            "target_light": target_light,
            "target_residual_image_id": residual_image,
        }

    def region_delta(
        self,
        region: str,
        source_image_id: str,
        target: dict[str, str],
    ) -> np.ndarray:
        region_library = self.library.loc[
            self.library["region"].astype(str) == region
        ]
        current = first_matching(
            region_library,
            image_id=source_image_id,
        )
        target_phone = first_matching(
            region_library,
            phone_id=target["target_phone"],
        )
        target_light = first_matching(
            region_library,
            light_id=target["target_light"],
        )
        target_interaction = first_matching(
            region_library,
            phone_id=target["target_phone"],
            light_id=target["target_light"],
        )
        target_residual = first_matching(
            region_library,
            image_id=target["target_residual_image_id"],
        )

        total = np.zeros(3, dtype=np.float64)
        total += self.phone_scale * (
            vector_from_row(target_phone, "phone_effect")
            - vector_from_row(current, "phone_effect")
        )
        total += self.light_scale * (
            vector_from_row(target_light, "light_effect")
            - vector_from_row(current, "light_effect")
        )
        total += self.interaction_scale * (
            vector_from_row(
                target_interaction,
                "interaction_effect",
            )
            - vector_from_row(current, "interaction_effect")
        )
        total += self.residual_scale * (
            vector_from_row(target_residual, "residual")
            - vector_from_row(current, "residual")
        )
        return self.overall_scale * total

    def apply(
        self,
        row: pd.Series,
        rng: random.Random,
    ) -> tuple[Image.Image, dict[str, Any]]:
        source_image_id = str(row["image_id"])
        source_phone = str(row["phone"])
        source_light = str(row["light"])

        target = self.sample_target(
            source_phone,
            source_light,
            rng,
        )
        bg_delta = self.region_delta(
            "bg",
            source_image_id,
            target,
        )
        contrast_delta = self.region_delta(
            "contrast",
            source_image_id,
            target,
        )

        crop = Image.open(row["__crop_path__"]).convert("RGB")
        rgb = np.asarray(crop, dtype=np.float64) / 255.0
        lab = srgb_to_lab(rgb)

        roi_bbox = (
            float(row["roi_crop_x1"]),
            float(row["roi_crop_y1"]),
            float(row["roi_crop_x2"]),
            float(row["roi_crop_y2"]),
        )
        feather = make_feather_mask(
            crop.size,
            roi_bbox,
            self.feather_radius,
        )

        lab_augmented = (
            lab
            + bg_delta.reshape(1, 1, 3)
            + feather[..., None]
            * contrast_delta.reshape(1, 1, 3)
        )
        rgb_unclipped = lab_to_srgb_unclipped(lab_augmented)
        clip_mask = np.any(
            (rgb_unclipped < 0.0) | (rgb_unclipped > 1.0),
            axis=-1,
        )
        output = Image.fromarray(
            np.round(
                np.clip(rgb_unclipped, 0.0, 1.0) * 255.0
            ).astype(np.uint8),
            mode="RGB",
        )
        model_input = letterbox_white(output, self.image_size)

        metadata = {
            **target,
            "bg_delta_E": float(np.linalg.norm(bg_delta)),
            "contrast_delta_E": float(
                np.linalg.norm(contrast_delta)
            ),
            "pad_total_delta_E": float(
                np.linalg.norm(bg_delta + contrast_delta)
            ),
            "rgb_gamut_clipped_ratio": float(clip_mask.mean()),
        }
        return model_input, metadata


class LocalContextDataset(Dataset):
    def __init__(
        self,
        frame: pd.DataFrame,
        method: str,
        image_size: int,
        nuisance_transfer: StructuredNuisanceTransfer | None,
        nuisance_probability: float,
        seed: int,
        jitter_settings: dict[str, float],
        training: bool,
    ) -> None:
        self.frame = frame.reset_index(drop=True).copy()
        self.method = method
        self.image_size = int(image_size)
        self.nuisance_transfer = nuisance_transfer
        self.nuisance_probability = float(nuisance_probability)
        self.seed = int(seed)
        self.training = bool(training)
        self.epoch = 0

        self.color_jitter = transforms.ColorJitter(
            brightness=jitter_settings["brightness"],
            contrast=jitter_settings["contrast"],
            saturation=jitter_settings["saturation"],
            hue=jitter_settings["hue"],
        )
        self.to_tensor = transforms.Compose([
            transforms.ToTensor(),
            transforms.Normalize(
                mean=IMAGENET_MEAN,
                std=IMAGENET_STD,
            ),
        ])

    def set_epoch(self, epoch: int) -> None:
        self.epoch = int(epoch)

    def __len__(self) -> int:
        return len(self.frame)

    def __getitem__(
        self,
        index: int,
    ) -> tuple[torch.Tensor, int, str]:
        row = self.frame.iloc[index]
        rng = random.Random(
            self.seed + 1_000_003 * self.epoch + index
        )

        if (
            self.training
            and self.method == "nuisance_structured"
            and rng.random() < self.nuisance_probability
        ):
            if self.nuisance_transfer is None:
                raise RuntimeError(
                    "Nuisance method requires a nuisance transformer."
                )
            image, _ = self.nuisance_transfer.apply(row, rng)
        else:
            image = Image.open(
                row["__model_input_path__"]
            ).convert("RGB")

        if self.training and self.method == "color_jitter":
            image = self.color_jitter(image)

        tensor = self.to_tensor(image)
        label = int(row["label_index"])
        return tensor, label, str(row["image_id"])


def make_dataloader(
    dataset: Dataset,
    batch_size: int,
    shuffle: bool,
    num_workers: int,
    seed: int,
) -> DataLoader:
    generator = torch.Generator()
    generator.manual_seed(seed)

    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
        generator=generator,
        persistent_workers=(num_workers > 0),
    )


def build_model(
    pretrained: bool,
    seed: int,
) -> nn.Module:
    set_global_seed(seed)

    if pretrained:
        try:
            model = resnet18(
                weights=ResNet18_Weights.DEFAULT
            )
        except Exception as exc:
            raise RuntimeError(
                "Could not load ImageNet ResNet18 weights. Ensure internet "
                "access for the first run or that the weights are cached. "
                "Do not silently replace this with scratch training."
            ) from exc
    else:
        model = resnet18(weights=None)

    input_features = model.fc.in_features
    model.fc = nn.Linear(input_features, len(LABEL_ORDER))
    set_trainable_stage(model, "warmup")
    return model


def set_trainable_stage(
    model: nn.Module,
    stage: str,
) -> None:
    """Choose trainable parameters without unfreezing the whole backbone."""
    if stage not in {"warmup", "finetune"}:
        raise ValueError(f"Unknown training stage: {stage}")

    for parameter in model.parameters():
        parameter.requires_grad = False

    for parameter in model.fc.parameters():
        parameter.requires_grad = True

    if stage == "finetune":
        for parameter in model.layer4.parameters():
            parameter.requires_grad = True


def freeze_batchnorm_statistics(module: nn.Module) -> None:
    """Keep pretrained BatchNorm running statistics fixed for small batches."""
    if isinstance(module, nn.modules.batchnorm._BatchNorm):
        module.eval()


def set_training_mode(
    model: nn.Module,
    stage: str,
) -> None:
    # Frozen layers remain in evaluation mode. During fine-tuning, layer4
    # convolutions train, but all BatchNorm running statistics stay fixed.
    model.eval()
    model.fc.train()

    if stage == "finetune":
        model.layer4.train()
        model.layer4.apply(freeze_batchnorm_statistics)


def build_optimizer(
    model: nn.Module,
    stage: str,
    head_learning_rate: float,
    layer4_learning_rate: float,
    weight_decay: float,
) -> torch.optim.Optimizer:
    if stage == "warmup":
        return torch.optim.AdamW(
            model.fc.parameters(),
            lr=head_learning_rate,
            weight_decay=weight_decay,
        )

    if stage == "finetune":
        return torch.optim.AdamW(
            [
                {
                    "params": model.layer4.parameters(),
                    "lr": layer4_learning_rate,
                },
                {
                    "params": model.fc.parameters(),
                    "lr": head_learning_rate,
                },
            ],
            weight_decay=weight_decay,
        )

    raise ValueError(f"Unknown optimizer stage: {stage}")


def calculate_metrics(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    probabilities: np.ndarray,
    average_loss: float,
) -> Metrics:
    return Metrics(
        loss=float(average_loss),
        accuracy=float(accuracy_score(y_true, y_pred)),
        balanced_accuracy=float(
            balanced_accuracy_score(y_true, y_pred)
        ),
        macro_f1=float(
            f1_score(
                y_true,
                y_pred,
                average="macro",
                zero_division=0,
            )
        ),
        n=int(len(y_true)),
    )


def run_epoch(
    model: nn.Module,
    dataloader: DataLoader,
    criterion: nn.Module,
    device: torch.device,
    optimizer: torch.optim.Optimizer | None,
    training_stage: str,
) -> tuple[Metrics, np.ndarray, np.ndarray, np.ndarray, list[str]]:
    training = optimizer is not None

    if training:
        set_training_mode(model, training_stage)
    else:
        model.eval()

    total_loss = 0.0
    total_items = 0
    all_true: list[int] = []
    all_pred: list[int] = []
    all_probabilities: list[np.ndarray] = []
    all_ids: list[str] = []

    context = torch.enable_grad() if training else torch.no_grad()
    with context:
        for images, labels, image_ids in dataloader:
            images = images.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)

            if training:
                optimizer.zero_grad(set_to_none=True)

            logits = model(images)
            loss = criterion(logits, labels)

            if training:
                loss.backward()
                optimizer.step()

            probabilities = torch.softmax(logits, dim=1)
            predictions = torch.argmax(probabilities, dim=1)

            batch_size = labels.shape[0]
            total_loss += float(loss.detach().cpu()) * batch_size
            total_items += batch_size

            all_true.extend(labels.detach().cpu().numpy().tolist())
            all_pred.extend(
                predictions.detach().cpu().numpy().tolist()
            )
            all_probabilities.extend(
                probabilities.detach().cpu().numpy()
            )
            all_ids.extend(list(image_ids))

    y_true = np.asarray(all_true, dtype=int)
    y_pred = np.asarray(all_pred, dtype=int)
    probability_array = np.asarray(
        all_probabilities,
        dtype=float,
    )
    average_loss = total_loss / max(total_items, 1)

    metrics = calculate_metrics(
        y_true,
        y_pred,
        probability_array,
        average_loss,
    )
    return (
        metrics,
        y_true,
        y_pred,
        probability_array,
        all_ids,
    )


def checkpoint_rank(metrics: Metrics) -> tuple[float, float, float]:
    return (
        metrics.macro_f1,
        metrics.balanced_accuracy,
        -metrics.loss,
    )


def prediction_frame(
    subset: pd.DataFrame,
    image_ids: Sequence[str],
    y_true: np.ndarray,
    y_pred: np.ndarray,
    probabilities: np.ndarray,
) -> pd.DataFrame:
    lookup = subset.set_index("image_id", drop=False)
    ordered = lookup.loc[list(image_ids)].reset_index(drop=True)

    output = pd.DataFrame({
        "image_id": image_ids,
        "split": ordered["__split__"].astype(str),
        "phone": ordered["phone"].astype(str),
        "light": ordered["light"].astype(str),
        "ph_nominal": ordered["ph_nominal"].astype(float),
        "true_index": y_true,
        "true_label": [
            LABEL_ORDER[index] for index in y_true
        ],
        "pred_index": y_pred,
        "pred_label": [
            LABEL_ORDER[index] for index in y_pred
        ],
        "probability_acidic": probabilities[:, 0],
        "probability_alkaline": probabilities[:, 1],
        "correct": y_true == y_pred,
    })
    return output


def save_confusion_and_report(
    run_dir: Path,
    split_name: str,
    predictions: pd.DataFrame,
) -> None:
    y_true = predictions["true_index"].to_numpy(dtype=int)
    y_pred = predictions["pred_index"].to_numpy(dtype=int)

    matrix = confusion_matrix(
        y_true,
        y_pred,
        labels=[0, 1],
    )
    pd.DataFrame(
        matrix,
        index=[f"true_{label}" for label in LABEL_ORDER],
        columns=[f"pred_{label}" for label in LABEL_ORDER],
    ).to_csv(
        run_dir / f"confusion_matrix_{split_name}.csv"
    )

    report = classification_report(
        y_true,
        y_pred,
        labels=[0, 1],
        target_names=LABEL_ORDER,
        output_dict=True,
        zero_division=0,
    )
    pd.DataFrame(report).transpose().to_csv(
        run_dir / f"classification_report_{split_name}.csv"
    )


def per_ph_summary(
    predictions: pd.DataFrame,
) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for ph_value, group in predictions.groupby(
        "ph_nominal",
        sort=True,
    ):
        rows.append({
            "ph_nominal": float(ph_value),
            "n": len(group),
            "accuracy": float(group["correct"].mean()),
            "mean_probability_alkaline": float(
                group["probability_alkaline"].mean()
            ),
            "min_probability_alkaline": float(
                group["probability_alkaline"].min()
            ),
            "max_probability_alkaline": float(
                group["probability_alkaline"].max()
            ),
        })
    return pd.DataFrame(rows)


def boundary_metrics(
    predictions: pd.DataFrame,
) -> dict[str, float]:
    output: dict[str, float] = {}
    for ph_value in [6.0, 8.0, 9.0, 12.0]:
        subset = predictions.loc[
            np.isclose(
                predictions["ph_nominal"].to_numpy(dtype=float),
                ph_value,
            )
        ]
        key = str(int(ph_value))
        output[f"ph{key}_accuracy"] = (
            float(subset["correct"].mean())
            if len(subset)
            else float("nan")
        )
        output[f"ph{key}_mean_probability_alkaline"] = (
            float(subset["probability_alkaline"].mean())
            if len(subset)
            else float("nan")
        )
    return output


def single_class_prediction(
    predictions: pd.DataFrame,
) -> bool:
    return predictions["pred_index"].nunique() < 2


def train_one_method(
    method: str,
    frame: pd.DataFrame,
    nuisance_transfer: StructuredNuisanceTransfer,
    args: argparse.Namespace,
    device: torch.device,
    output_dir: Path,
) -> dict[str, Any]:
    method_seed = args.seed
    set_global_seed(method_seed)

    train_frame = frame.loc[
        frame["__split__"] == "train"
    ].copy()
    val_frame = frame.loc[
        frame["__split__"] == "val"
    ].copy()
    test_frame = frame.loc[
        frame["__split__"] == "test"
    ].copy()

    jitter_settings = {
        "brightness": args.jitter_brightness,
        "contrast": args.jitter_contrast,
        "saturation": args.jitter_saturation,
        "hue": args.jitter_hue,
    }

    train_dataset = LocalContextDataset(
        frame=train_frame,
        method=method,
        image_size=args.image_size,
        nuisance_transfer=nuisance_transfer,
        nuisance_probability=args.nuisance_probability,
        seed=method_seed,
        jitter_settings=jitter_settings,
        training=True,
    )
    val_dataset = LocalContextDataset(
        frame=val_frame,
        method="baseline",
        image_size=args.image_size,
        nuisance_transfer=None,
        nuisance_probability=0.0,
        seed=method_seed,
        jitter_settings=jitter_settings,
        training=False,
    )
    test_dataset = LocalContextDataset(
        frame=test_frame,
        method="baseline",
        image_size=args.image_size,
        nuisance_transfer=None,
        nuisance_probability=0.0,
        seed=method_seed,
        jitter_settings=jitter_settings,
        training=False,
    )

    train_loader = make_dataloader(
        train_dataset,
        args.batch_size,
        True,
        args.num_workers,
        method_seed,
    )
    val_loader = make_dataloader(
        val_dataset,
        args.batch_size,
        False,
        args.num_workers,
        method_seed,
    )
    test_loader = make_dataloader(
        test_dataset,
        args.batch_size,
        False,
        args.num_workers,
        method_seed,
    )

    model = build_model(
        pretrained=not args.no_pretrained,
        seed=method_seed,
    ).to(device)
    criterion = nn.CrossEntropyLoss()

    method_dir = output_dir / method
    method_dir.mkdir(parents=True, exist_ok=True)

    history_rows: list[dict[str, Any]] = []
    best_state: dict[str, torch.Tensor] | None = None
    best_val_metrics: Metrics | None = None
    best_global_epoch = -1
    best_stage = ""
    best_stage_epoch = -1
    global_epoch = 0

    def run_training_epoch(
        stage: str,
        stage_epoch: int,
        stage_total: int,
        optimizer: torch.optim.Optimizer,
    ) -> tuple[Metrics, Metrics, bool]:
        nonlocal best_state
        nonlocal best_val_metrics
        nonlocal best_global_epoch
        nonlocal best_stage
        nonlocal best_stage_epoch
        nonlocal global_epoch

        global_epoch += 1
        train_dataset.set_epoch(global_epoch)

        train_metrics, *_ = run_epoch(
            model,
            train_loader,
            criterion,
            device,
            optimizer,
            stage,
        )
        val_metrics, *_ = run_epoch(
            model,
            val_loader,
            criterion,
            device,
            None,
            stage,
        )

        history_rows.append({
            "global_epoch": global_epoch,
            "stage": stage,
            "stage_epoch": stage_epoch,
            "stage_total_epochs": stage_total,
            "head_learning_rate": args.head_learning_rate,
            "layer4_learning_rate": (
                args.layer4_learning_rate
                if stage == "finetune"
                else 0.0
            ),
            "train_loss": train_metrics.loss,
            "train_accuracy": train_metrics.accuracy,
            "train_balanced_accuracy": (
                train_metrics.balanced_accuracy
            ),
            "train_macro_f1": train_metrics.macro_f1,
            "val_loss": val_metrics.loss,
            "val_accuracy": val_metrics.accuracy,
            "val_balanced_accuracy": (
                val_metrics.balanced_accuracy
            ),
            "val_macro_f1": val_metrics.macro_f1,
        })

        print(
            f"[{method}] {stage} "
            f"{stage_epoch:02d}/{stage_total} "
            f"(global {global_epoch:02d}) | "
            f"train f1={train_metrics.macro_f1:.3f} "
            f"bal={train_metrics.balanced_accuracy:.3f} | "
            f"val f1={val_metrics.macro_f1:.3f} "
            f"bal={val_metrics.balanced_accuracy:.3f} "
            f"loss={val_metrics.loss:.4f}"
        )

        improved = (
            best_val_metrics is None
            or checkpoint_rank(val_metrics)
            > checkpoint_rank(best_val_metrics)
        )
        if improved:
            best_val_metrics = copy.deepcopy(val_metrics)
            best_global_epoch = global_epoch
            best_stage = stage
            best_stage_epoch = stage_epoch
            best_state = {
                key: value.detach().cpu().clone()
                for key, value in model.state_dict().items()
            }

        return train_metrics, val_metrics, improved

    # Stage 1: train only the final classification head.
    set_trainable_stage(model, "warmup")
    warmup_optimizer = build_optimizer(
        model=model,
        stage="warmup",
        head_learning_rate=args.head_learning_rate,
        layer4_learning_rate=args.layer4_learning_rate,
        weight_decay=args.weight_decay,
    )

    for stage_epoch in range(1, args.warmup_epochs + 1):
        run_training_epoch(
            "warmup",
            stage_epoch,
            args.warmup_epochs,
            warmup_optimizer,
        )

    if best_state is None or best_val_metrics is None:
        raise RuntimeError("Warm-up did not create a validation checkpoint.")

    # Start layer4 fine-tuning from the best warm-up checkpoint, not merely
    # from the last warm-up epoch.
    model.load_state_dict(best_state)
    set_trainable_stage(model, "finetune")
    finetune_optimizer = build_optimizer(
        model=model,
        stage="finetune",
        head_learning_rate=args.head_learning_rate,
        layer4_learning_rate=args.layer4_learning_rate,
        weight_decay=args.weight_decay,
    )

    epochs_without_global_improvement = 0
    for stage_epoch in range(1, args.finetune_epochs + 1):
        _, _, improved = run_training_epoch(
            "finetune",
            stage_epoch,
            args.finetune_epochs,
            finetune_optimizer,
        )

        if improved:
            epochs_without_global_improvement = 0
        else:
            epochs_without_global_improvement += 1

        if (
            stage_epoch >= args.min_finetune_epochs
            and epochs_without_global_improvement >= args.patience
        ):
            print(
                f"[{method}] fine-tuning early stop after "
                f"stage epoch {stage_epoch}; global best="
                f"{best_stage} epoch {best_stage_epoch} "
                f"(global epoch {best_global_epoch})."
            )
            break

    if best_state is None or best_val_metrics is None:
        raise RuntimeError("No validation checkpoint was created.")

    model.load_state_dict(best_state)
    torch.save(
        {
            "model_state_dict": best_state,
            "method": method,
            "best_global_epoch": best_global_epoch,
            "best_stage": best_stage,
            "best_stage_epoch": best_stage_epoch,
            "labels": LABEL_ORDER,
            "pretrained": not args.no_pretrained,
            "training_strategy": "head_warmup_then_layer4_finetune",
            "batchnorm_statistics_frozen": True,
        },
        method_dir / "best_model.pt",
    )

    history = pd.DataFrame(history_rows)
    history.to_csv(
        method_dir / "training_history.csv",
        index=False,
    )

    evaluation_train_dataset = LocalContextDataset(
        frame=train_frame,
        method="baseline",
        image_size=args.image_size,
        nuisance_transfer=None,
        nuisance_probability=0.0,
        seed=method_seed,
        jitter_settings=jitter_settings,
        training=False,
    )
    evaluation_train_loader = make_dataloader(
        evaluation_train_dataset,
        args.batch_size,
        False,
        args.num_workers,
        method_seed,
    )

    split_results: dict[str, tuple[Metrics, pd.DataFrame]] = {}
    for split_name, subset, loader in [
        ("train", train_frame, evaluation_train_loader),
        ("val", val_frame, val_loader),
        ("test", test_frame, test_loader),
    ]:
        (
            metrics,
            y_true,
            y_pred,
            probabilities,
            image_ids,
        ) = run_epoch(
            model,
            loader,
            criterion,
            device,
            None,
            "finetune",
        )
        predictions = prediction_frame(
            subset,
            image_ids,
            y_true,
            y_pred,
            probabilities,
        )
        predictions.to_csv(
            method_dir / f"predictions_{split_name}.csv",
            index=False,
        )
        save_confusion_and_report(
            method_dir,
            split_name,
            predictions,
        )
        split_results[split_name] = (metrics, predictions)

    test_metrics, test_predictions = split_results["test"]
    per_ph_summary(test_predictions).to_csv(
        method_dir / "test_metrics_by_ph.csv",
        index=False,
    )

    config = {
        "method": method,
        "best_global_epoch": best_global_epoch,
        "best_stage": best_stage,
        "best_stage_epoch": best_stage_epoch,
        "best_validation_metrics": asdict(best_val_metrics),
        "pretrained": not args.no_pretrained,
        "training_strategy": "head_warmup_then_layer4_finetune",
        "batchnorm_statistics_frozen": True,
        "warmup_epochs": args.warmup_epochs,
        "finetune_epochs": args.finetune_epochs,
        "head_learning_rate": args.head_learning_rate,
        "layer4_learning_rate": args.layer4_learning_rate,
        "image_size": args.image_size,
        "jitter": jitter_settings,
        "nuisance_probability": args.nuisance_probability,
        "seed": method_seed,
    }
    with (method_dir / "run_config.json").open(
        "w", encoding="utf-8"
    ) as handle:
        json.dump(config, handle, ensure_ascii=False, indent=2)

    result = {
        "method": method,
        "best_global_epoch": best_global_epoch,
        "best_stage": best_stage,
        "best_stage_epoch": best_stage_epoch,
        "best_val_loss": best_val_metrics.loss,
        "best_val_accuracy": best_val_metrics.accuracy,
        "best_val_balanced_accuracy": (
            best_val_metrics.balanced_accuracy
        ),
        "best_val_macro_f1": best_val_metrics.macro_f1,
        "test_loss": test_metrics.loss,
        "test_accuracy": test_metrics.accuracy,
        "test_balanced_accuracy": (
            test_metrics.balanced_accuracy
        ),
        "test_macro_f1": test_metrics.macro_f1,
        "test_single_class_prediction": (
            single_class_prediction(test_predictions)
        ),
        **boundary_metrics(test_predictions),
    }
    return result


def save_nuisance_preview(
    frame: pd.DataFrame,
    transformer: StructuredNuisanceTransfer,
    output_dir: Path,
    seed: int,
    count: int = 12,
) -> None:
    train = frame.loc[
        frame["__split__"] == "train"
    ].sort_values(
        ["phone", "light", "ph_nominal", "image_id"]
    )
    selected = train.head(min(count, len(train)))
    output_dir.mkdir(parents=True, exist_ok=True)
    rng = random.Random(seed)

    metadata: list[dict[str, Any]] = []
    for index, (_, row) in enumerate(selected.iterrows(), start=1):
        augmented, info = transformer.apply(row, rng)
        path = output_dir / (
            f"{index:03d}__{row['image_id']}__nuisance.png"
        )
        augmented.save(path)
        metadata.append({
            "image_id": row["image_id"],
            "phone": row["phone"],
            "light": row["light"],
            "ph_nominal": row["ph_nominal"],
            "output_path": str(path),
            **info,
        })
    pd.DataFrame(metadata).to_csv(
        output_dir / "preview_metadata.csv",
        index=False,
    )


